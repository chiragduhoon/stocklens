import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const out=new URL('../test-results/previews/',import.meta.url);
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
await page.goto('http://127.0.0.1:8000/');
await page.getByRole('heading',{name:'Your portfolio, in perspective.'}).waitFor();
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:new URL('overview-desktop.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
await page.getByRole('button',{name:'Analyze INFY',exact:true}).click();
await page.getByRole('button',{name:'Analyst research',exact:true}).waitFor();
await page.screenshot({path:new URL('stock-research.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
await page.keyboard.press('Escape');
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:8000/');
await page.getByRole('heading',{name:'Your portfolio, in perspective.'}).waitFor();
await page.screenshot({path:new URL('overview-mobile.png',out).pathname.replace(/^\/([A-Za-z]:)/,'$1'),fullPage:true});
await browser.close();
console.log('Saved desktop, stock detail, and mobile screenshots.');
